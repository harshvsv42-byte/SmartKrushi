class MarketPricesView(APIView):
    permission_classes = [AllowAny]

    def get(self, request):
        crop_filter = request.query_params.get('crop', '').strip().lower()
        district_filter = request.query_params.get('district', '').strip().lower()
        mandi_filter = request.query_params.get('mandi', '').strip().lower()
        category_filter = request.query_params.get('category', '').strip().lower()

        prices = get_base_prices()

        if mandi_filter and mandi_filter != 'all':
            prices = [
                p for p in prices
                if mandi_filter in p["mandi"].lower()
                or mandi_filter in p.get("mandi_gu", "").lower()
                or mandi_filter in p.get("district", "").lower()
            ]

        if category_filter and category_filter != 'all':
            prices = [p for p in prices if p.get("category", "").lower() == category_filter]

        if crop_filter:
            prices = [
                p for p in prices
                if crop_filter in p["crop_name"].lower()
                or crop_filter in p.get("crop_name_gu", "").lower()
                or crop_filter in p.get("variety", "").lower()
            ]

        if district_filter:
            prices = [
                p for p in prices
                if district_filter in p["district"].lower()
                or district_filter in p["mandi"].lower()
            ]

        # If client requested json structure with mandis and categories metadata:
        include_meta = request.query_params.get('include_meta', 'false').lower() == 'true'
        if include_meta:
            return Response({
                "prices": prices,
                "mandis": GUJARAT_MANDIS,
                "categories": GUJARAT_CATEGORIES,
                "last_updated": datetime.datetime.now().strftime("%d-%m-%Y %I:%M %p"),
                "total_items": len(prices)
            })

        return Response(prices)


